$targetDir = "X:\BaiduNetdiskDownload\nodejs"
Write-Host "开始扫描并删除 node_modules 文件夹..." -ForegroundColor Cyan
Write-Host ""

$folders = Get-ChildItem -Path $targetDir -Recurse -Directory -Filter "node_modules"
$count = 0

foreach ($folder in $folders) {
    Write-Host "正在删除: $($folder.FullName)" -ForegroundColor Yellow
    Remove-Item -Path $folder.FullName -Recurse -Force
    $count++
}

Write-Host ""
Write-Host "完成! 共删除 $count 个 node_modules 文件夹" -ForegroundColor Green
Read-Host "按回车键退出"
